"""Conservative, uncalibrated audio synthesis for tinnitus sound enrichment.

No signal generated by this module is a proven tinnitus treatment. The digital
amplitude cap is not a sound-pressure-level limit: devices vary substantially.
"""

from dataclasses import dataclass
from io import BytesIO
import wave

import numpy as np
from scipy import signal

SAMPLE_RATE = 44_100
SOUND_TYPES = ("Pink noise", "White noise", "Brown noise")


@dataclass(frozen=True)
class AudioSettings:
    sound_type: str = "Pink noise"
    low_hz: int = 150
    high_hz: int = 4500
    tone_hz: int = 440
    tone_mix_percent: int = 0
    digital_peak_percent: int = 5
    duration_seconds: int = 30

    def validate(self) -> None:
        if self.sound_type not in SOUND_TYPES:
            raise ValueError("Unknown sound type")
        if not 80 <= self.low_hz < self.high_hz <= 8000:
            raise ValueError("Frequency limits must be 80–8000 Hz, lower < upper")
        if not 125 <= self.tone_hz <= 2000:
            raise ValueError("Gentle tone must be between 125 and 2000 Hz")
        if not 0 <= self.tone_mix_percent <= 30:
            raise ValueError("Tone mix must be 0–30%")
        if not 1 <= self.digital_peak_percent <= 15:
            raise ValueError("Digital peak must be 1–15%")
        if self.duration_seconds not in (15, 30, 60, 120):
            raise ValueError("Duration must be 15, 30, 60 or 120 seconds")


def _coloured_noise(colour: str, size: int, seed: int) -> np.ndarray:
    """Create noise with approximate power spectra 1/f^alpha.

    White has alpha=0, pink alpha=1, and brown alpha=2. A 25 Hz floor
    avoids DC amplification. This is signal processing, not a therapeutic dose.
    """
    rng = np.random.default_rng(seed)
    x = rng.standard_normal(size).astype(np.float32)
    if colour == "White noise":
        return x
    alpha = 1.0 if colour == "Pink noise" else 2.0
    spectrum = np.fft.rfft(x)
    frequencies = np.fft.rfftfreq(size, d=1 / SAMPLE_RATE)
    weighting = np.maximum(frequencies, 25.0) ** (-alpha / 2.0)
    spectrum *= weighting
    spectrum[0] = 0
    return np.fft.irfft(spectrum, n=size).astype(np.float32)


def generate_samples(settings: AudioSettings, seed: int = 2026) -> np.ndarray:
    """Return fade-shaped mono float32 signal in [-peak/100, +peak/100]."""
    settings.validate()
    n = settings.duration_seconds * SAMPLE_RATE
    x = _coloured_noise(settings.sound_type, n, seed)
    # The Butterworth band-pass simply changes the noise timbre; it does not
    # target the tinnitus pitch and has no established disease-modifying effect.
    sos = signal.butter(
        3,
        [settings.low_hz, settings.high_hz],
        btype="bandpass",
        fs=SAMPLE_RATE,
        output="sos",
    )
    x = signal.sosfilt(sos, x).astype(np.float32)
    max_abs = float(np.max(np.abs(x)))
    if max_abs < 1e-12:
        raise RuntimeError("Unable to normalise the generated sound")
    x /= max_abs

    mixture = settings.tone_mix_percent / 100.0
    if mixture > 0:
        t = np.arange(n, dtype=np.float32) / SAMPLE_RATE
        # Gentle low-frequency envelope avoids a perfectly steady tone.
        envelope = 0.85 + 0.15 * np.sin(2 * np.pi * 0.17 * t)
        tone = (np.sin(2 * np.pi * settings.tone_hz * t) * envelope).astype(
            np.float32
        )
        x = ((1 - mixture) * x + mixture * tone).astype(np.float32)

    # Output amplitude is limited *digitally*. It is not calibrated in dB SPL.
    x *= settings.digital_peak_percent / 100.0
    fade_samples = min(int(0.18 * SAMPLE_RATE), n // 4)
    ramp = np.linspace(0.0, 1.0, fade_samples, dtype=np.float32)
    x[:fade_samples] *= ramp
    x[-fade_samples:] *= ramp[::-1]
    return x


def generate_wav(settings: AudioSettings, seed: int = 2026) -> bytes:
    """Generate 16-bit mono PCM WAV for manual playback or download."""
    x = generate_samples(settings, seed=seed)
    pcm = np.round(np.clip(x, -1, 1) * 32767).astype("<i2")
    result = BytesIO()
    with wave.open(result, "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(SAMPLE_RATE)
        out.writeframes(pcm.tobytes())
    return result.getvalue()
